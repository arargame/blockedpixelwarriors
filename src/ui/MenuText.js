export const LANGUAGE_NAMES = Object.freeze({ en: 'ENGLISH', tr: 'TÜRKÇE' });

/** Menu string in the given language (falls back to English), `{n}` style placeholders filled. */
export function menuText(lang, key, vars = null) {
  let s = MENU_TEXT[lang]?.[key] ?? MENU_TEXT.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}
